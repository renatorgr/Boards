// FW_NAME and FW_VERSION show on the web page (Firmware) and in the [boot] / [web] lines.
#ifndef ZVERSION_H
#define ZVERSION_H

#define FW_VERSION       "7.2"
#define FW_NAME          "v" FW_VERSION "_UM982_X20P_F9P_TM171_WEB_XIAO"

#endif
